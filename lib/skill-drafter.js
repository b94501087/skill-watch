const fs = require('fs');
const path = require('path');
const { redact, redactSession } = require('./redactor');
const { loadHistory, loadSession, pendingDir, ensureDir } = require('./store');

function latestSession() {
  const current = loadSession();
  if (current && ((current.tools || []).length || (current.prompts || []).length)) {
    return redactSession(current);
  }
  const history = loadHistory();
  if (!history.sessions || !history.sessions.length) return null;
  return redactSession(history.sessions[history.sessions.length - 1]);
}

function generateSkillMd(name, session) {
  const tools = session.tools || [];
  const prompts = session.prompts || [];
  const toolList = tools.length ? tools.map((t) => `- ${t.name}`).join('\n') : '- (none recorded)';
  const stepList = tools.length
    ? tools.map((t, i) => `${i + 1}. Use \`${t.name}\`${t.input ? ` with ${String(t.input).slice(0, 80)}` : ''}`).join('\n')
    : '1. Review the recorded prompts and fill in the steps.';
  const promptSummary = prompts.length
    ? redact(String(prompts[0].text || '')).slice(0, 120)
    : 'Repeated workflow detected by skill-watch';

  return `---
name: ${name}
description: ${promptSummary}
---

# ${name}

## Purpose

This skill was drafted from a repeated local workflow. Review and edit it before installing.

## Tools used

${toolList}

## Steps

${stepList}

## Notes

- Generated by skill-watch as a draft only
- Sensitive values were redacted automatically
- Do not install until a person has reviewed this file
- Optional: hand this draft to skill-creator to refine and test it
`;
}

function safeName(name) {
  const cleaned = String(name || 'workflow')
    .toLowerCase()
    .replace(/[^a-z0-9\u4e00-\u9fff-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
  return cleaned || 'workflow';
}

function draftSkill(name) {
  const session = latestSession();
  if (!session) {
    return { success: false, error: 'No pattern data found' };
  }
  const skillName = safeName(name || 'workflow');
  const content = generateSkillMd(skillName, session);
  ensureDir(pendingDir());
  const filePath = path.join(pendingDir(), `${skillName}.md`);
  fs.writeFileSync(filePath, content);
  return { success: true, path: filePath, name: skillName };
}

function getStatus() {
  const { loadConfig } = require('./config');
  const { loadNudgeState } = require('./store');
  const history = loadHistory();
  const current = loadSession();
  const nudges = loadNudgeState();
  return {
    sessions: history.sessions?.length || 0,
    patterns: history.patterns || {},
    currentTools: (current.tools || []).length,
    currentPrompts: (current.prompts || []).length,
    lastNudge: nudges.lastByPattern || {},
    config: loadConfig(),
  };
}

module.exports = { draftSkill, getStatus, latestSession, generateSkillMd, safeName };
